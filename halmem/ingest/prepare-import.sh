#!/usr/bin/env bash
#
# prepare-import.sh — ONE command to prepare a folder of files for import into the vault.
#
# Runs every text extractor (PDF, DOCX, PPTX, HTML) over the folder so the local text-only
# model can summarise the decks, inventories Markdown notes (already text → import as-is),
# and writes a SINGLE combined SLIDES-REPORT.md. Use this instead of running each
# extract-*.sh by hand. Re-runnable; nothing is moved or summarised here (that's the
# /import-vault and /summarize-slides skills).
#
# Usage:
#   hal-memory import prepare               # scan _Import-Staging/ (the default)
#   hal-memory import prepare /path/to/Dir  # scan a specific folder
#   hal-memory import prepare --ocr         # also OCR scanned/image-only PDFs (needs tesseract)
#   hal-memory import prepare /path --ocr --force
#
set -uo pipefail

HERE="$(cd "$(dirname "$(readlink -f "${BASH_SOURCE[0]}")")" && pwd)"
# The vault is [hal].vault in ~/.config/hal/config.toml; HAL_VAULT overrides it for one run.
VAULT="${HAL_VAULT:-$(PYTHONPATH="$HERE/.." python3 -c 'from halmem.config import vault; print(vault())')}"

c_blue=$'\033[1;36m'; c_yellow=$'\033[1;33m'; c_green=$'\033[1;32m'; c_red=$'\033[1;31m'; c_off=$'\033[0m'
log()  { printf '\n%s==> %s%s\n' "$c_blue" "$*" "$c_off"; }
ok()   { printf '%s  ✓ %s%s\n' "$c_green" "$*" "$c_off"; }
warn() { printf '%s  ! %s%s\n' "$c_yellow" "$*" "$c_off"; }
err()  { printf '%s  ✗ %s%s\n' "$c_red" "$*" "$c_off"; }

# ---- Args -------------------------------------------------------------------
SCAN_DIR=""; PASS=()
for a in "$@"; do
  case "$a" in
    --ocr|--force) PASS+=( "$a" ) ;;
    -h|--help) sed -n '3,18p' "$0" | sed 's/^# \{0,1\}//'; exit 0 ;;
    *) [ -z "$SCAN_DIR" ] && SCAN_DIR="$a" ;;
  esac
done
[ -z "$SCAN_DIR" ] && SCAN_DIR="$VAULT/_Import-Staging"
if [ ! -d "$SCAN_DIR" ]; then
  err "Not a directory: $SCAN_DIR (stage your files first with: hal-memory import stage /path/to/OldVault)"; exit 1
fi
SCAN_DIR="$(cd "$SCAN_DIR" && pwd)"

export HAL_VAULT="$VAULT"                 # children inherit the same vault
REPORT="$VAULT/_Import-Staging/SLIDES-REPORT.md"
mkdir -p "$VAULT/_Import-Staging"
ALLROWS="$(mktemp)"; : > "$ALLROWS"
trap 'rm -f "$ALLROWS"' EXIT

declare -A T_TOTAL T_EXTRACT T_GAP
ORDER=()

# Pull the data rows out of whatever SLIDES-REPORT.md the last extractor wrote, tally them,
# and accumulate into ALLROWS — before the next extractor overwrites the file.
harvest() {  # $1=type label
  local t="$1" rows
  ORDER+=( "$t" ); T_TOTAL[$t]=0; T_EXTRACT[$t]=0; T_GAP[$t]=0
  [ -f "$REPORT" ] || return
  rows="$(awk '/^\|[ ]*-/{r=1;next} /^## *Summary/{r=0} r&&/^\| /{print}' "$REPORT")"
  [ -z "$rows" ] && return
  T_TOTAL[$t]="$(printf '%s\n' "$rows" | grep -c '^|')"
  T_EXTRACT[$t]="$(printf '%s\n' "$rows" | awk -F'|' '{v=$5; gsub(/[ \t]/,"",v)} v=="text"||v=="ocr"{c++} END{print c+0}')"
  T_GAP[$t]="$(printf '%s\n' "$rows" | grep -c '❌')"
  printf '%s\n' "$rows" >> "$ALLROWS"
}

run() {  # $1=script  $2=type label
  local s="$1" t="$2"
  if [ ! -f "$HERE/$s" ]; then warn "$s not found — skipping $t"; return; fi
  log "Extracting ${t}…"
  bash "$HERE/$s" "$SCAN_DIR" ${PASS[@]+"${PASS[@]}"} >/dev/null 2>&1 || warn "$s reported a problem (continuing)"
  harvest "$t"
  ok "${t}: ${T_TOTAL[$t]} found · ${T_EXTRACT[$t]} with text · ${T_GAP[$t]} need a summary"
}

# ---- Run every extractor ----------------------------------------------------
run extract-pdfs.sh  PDF
run extract-docx.sh  DOCX
run extract-pptx.sh  PPTX
run extract-html.sh  HTML

# ---- Markdown + other files (already text → import as-is) --------------------
md_filter=( ! -path '*/.pdf-text/*' ! -path '*/.docx-text/*' ! -path '*/.pptx-text/*'
            ! -path '*/.html-text/*' ! -name 'SLIDES-REPORT.md' ! -name 'IMPORT-MANIFEST*.md' )
MD_COUNT="$(find "$SCAN_DIR" -type f -iname '*.md' "${md_filter[@]}" 2>/dev/null | wc -l | tr -d ' ')"
ATTACH="$(find "$SCAN_DIR" -type f \( -iname '*.png' -o -iname '*.jpg' -o -iname '*.jpeg' \
  -o -iname '*.gif' -o -iname '*.webp' -o -iname '*.svg' -o -iname '*.mp4' -o -iname '*.mp3' \
  -o -iname '*.xlsx' -o -iname '*.csv' \) 2>/dev/null | wc -l | tr -d ' ')"

# ---- Totals -----------------------------------------------------------------
sum() { local s=0 v; for v in "$@"; do s=$((s + v)); done; echo "$s"; }
G_TOTAL="$(grep -c '^|' "$ALLROWS" 2>/dev/null || echo 0)"
G_EXTRACT="$(sum ${T_EXTRACT[@]+"${T_EXTRACT[@]}"})"
G_GAP="$(sum ${T_GAP[@]+"${T_GAP[@]}"})"

# ---- Write the single combined report --------------------------------------
{
  echo "---"
  echo "type: note"
  echo "tags: [system, import, slides]"
  echo "date: $(date +%F)"
  echo "---"
  echo
  echo "# Slides & Documents Report"
  echo
  echo "> Generated by \`prepare-import.sh\` on $(date '+%Y-%m-%d %H:%M'). Scanned: \`$SCAN_DIR\`"
  echo "> Combined across PDF / DOCX / PPTX / HTML. \`/summarize-slides\` fills summaries for"
  echo "> rows marked **❌ none**, reading each row's cached text from the **Cache** column."
  echo
  echo "| File | Course (folder) | Pages | Text | Existing summary | Cache |"
  echo "|---|---|---|---|---|---|"
  if [ -s "$ALLROWS" ]; then cat "$ALLROWS"; else echo "| _(no PDF/DOCX/PPTX/HTML files found)_ |  |  |  |  |  |"; fi
  echo
  echo "## Summary"
  echo
  echo "- Documents found (all types): **$G_TOTAL**"
  for t in ${ORDER[@]+"${ORDER[@]}"}; do
    echo "    - $t: ${T_TOTAL[$t]} found, ${T_EXTRACT[$t]} with text, ${T_GAP[$t]} to summarise"
  done
  echo "- Text successfully extracted: **$G_EXTRACT**"
  echo "- **Gaps to summarise (no note yet): $G_GAP**"
  echo "- Markdown notes (already text — import as-is): **$MD_COUNT**"
  echo "- Other attachments (images/media/sheets): **$ATTACH**"
  echo
  echo "Next:"
  echo "1. \`hal\` → \`/import-vault\` — file the **$MD_COUNT** Markdown notes into \`Areas/\`."
  echo "2. \`hal\` → \`/summarize-slides\` — generate notes for the **$G_GAP** gap decks."
} > "$REPORT"

# ---- Terminal summary -------------------------------------------------------
cat <<EOF

${c_green}Import preparation complete.${c_off}
  Documents found:   $G_TOTAL  (PDF ${T_TOTAL[PDF]:-0} · DOCX ${T_TOTAL[DOCX]:-0} · PPTX ${T_TOTAL[PPTX]:-0} · HTML ${T_TOTAL[HTML]:-0})
  Text extracted:    $G_EXTRACT
  ${c_yellow}Decks to summarise: $G_GAP${c_off}
  Markdown notes:    $MD_COUNT  (already text — ready to import)
  Other attachments: $ATTACH

Report: ${REPORT#$VAULT/}  (open it in Obsidian)
Next:   hal  →  /import-vault   (your notes)   then   /summarize-slides   (the decks)
EOF
