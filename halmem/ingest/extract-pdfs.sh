#!/usr/bin/env bash
#
# extract-pdfs.sh -- pull text out of lecture-slide PDFs so the local (text-only) model
# can summarise them, and report which decks DON'T already have a summary note.
#
# It writes one .txt per PDF into a cache, plus SLIDES-REPORT.md. It does NOT summarise or
# move anything -- that's the /summarize-slides skill. Re-runnable (skips already-extracted).
#
# Usage:
#   hal-memory import extract pdf                  # scan everything under _Import-Staging/
#   hal-memory import extract pdf /path/to/Slides  # scan a specific folder (also staged or not)
#   hal-memory import extract pdf --ocr            # also OCR scanned/image-only PDFs (needs tesseract)
#   hal-memory import extract pdf /path/to/Slides --ocr --force
#
set -uo pipefail

HERE="$(cd "$(dirname "$(readlink -f "${BASH_SOURCE[0]}")")" && pwd)"
# The vault is [hal].vault in ~/.config/hal/config.toml; HAL_VAULT overrides it for one run.
VAULT="${HAL_VAULT:-$(PYTHONPATH="$HERE/.." python3 -c 'from halmem.config import vault; print(vault())')}"

c_blue=$'\033[1;36m'; c_yellow=$'\033[1;33m'; c_green=$'\033[1;32m'; c_red=$'\033[1;31m'; c_off=$'\033[0m'
log()  { printf '\n%s==> %s%s\n' "$c_blue" "$*" "$c_off"; }
ok()   { printf '%s  [ok] %s%s\n' "$c_green" "$*" "$c_off"; }
warn() { printf '%s  ! %s%s\n' "$c_yellow" "$*" "$c_off"; }
err()  { printf '%s  [fail] %s%s\n' "$c_red" "$*" "$c_off"; }
have() { command -v "$1" >/dev/null 2>&1; }

# ---- Args -------------------------------------------------------------------
SCAN_DIR=""; DO_OCR=0; FORCE=0
for a in "$@"; do
  case "$a" in
    --ocr) DO_OCR=1 ;;
    --force) FORCE=1 ;;
    *) [ -z "$SCAN_DIR" ] && SCAN_DIR="$a" ;;
  esac
done
[ -z "$SCAN_DIR" ] && SCAN_DIR="$VAULT/_Import-Staging"
if [ ! -d "$SCAN_DIR" ]; then err "Not a directory: $SCAN_DIR (stage your files first with: hal-memory import stage /path/to/OldVault)"; exit 1; fi
SCAN_DIR="$(cd "$SCAN_DIR" && pwd)"

CACHE="$VAULT/_Import-Staging/.pdf-text"
REPORT="$VAULT/_Import-Staging/SLIDES-REPORT.md"
mkdir -p "$CACHE" "$VAULT/_Import-Staging"

if ! have pdftotext && ! python3 -c 'import fitz' >/dev/null 2>&1; then
  err "No PDF extractor found. Install poppler-utils (pdftotext) or pymupdf, see: hal-memory setup --check"
  exit 1
fi
MIN_CHARS=30   # below this, pdftotext got essentially nothing -> image-only / needs OCR

extract_text() {  # $1=pdf  $2=out.txt  -> echoes char count
  local pdf="$1" out="$2"
  : > "$out"   # ensure the output file exists even if every extractor yields nothing
  if have pdftotext; then
    pdftotext -layout "$pdf" "$out" 2>/dev/null || :
  fi
  if [ ! -s "$out" ] && python3 -c 'import fitz' >/dev/null 2>&1; then
    python3 - "$pdf" "$out" <<'PY' 2>/dev/null || :
import sys, fitz
doc = fitz.open(sys.argv[1])
open(sys.argv[2], "w").write("\n".join(p.get_text() for p in doc))
PY
  fi
  wc -m < "$out" 2>/dev/null | tr -d ' ' || echo 0
}

ocr_pdf() {  # $1=pdf  $2=out.txt  -> echoes char count
  local pdf="$1" out="$2" tmpd
  if ! have tesseract || ! have pdftoppm; then echo 0; return; fi
  tmpd="$(mktemp -d)"
  pdftoppm -r 150 -png "$pdf" "$tmpd/p" >/dev/null 2>&1
  : > "$out"
  for img in "$tmpd"/p*.png; do
    [ -e "$img" ] || continue
    tesseract "$img" stdout 2>/dev/null >> "$out"
  done
  rm -rf "$tmpd"
  wc -m < "$out" 2>/dev/null | tr -d ' ' || echo 0
}

# Does a summary note already exist for this deck?
find_summary() {  # $1=pdf path -> echoes "status|candidate"
  local pdf="$1" stem base hit
  base="$(basename "$pdf")"
  stem="${base%.pdf}"
  # (a) same-stem .md anywhere in vault
  hit="$(find "$SCAN_DIR" "$VAULT/Areas" -type f -name "$stem.md" 2>/dev/null | head -n1)"
  if [ -n "$hit" ]; then echo "yes|${hit#$VAULT/}"; return; fi
  # (b) a note that already declares this pdf as its source, or embeds/links it
  hit="$(grep -rlF --include='*.md' "$base" "$SCAN_DIR" "$VAULT/Areas" 2>/dev/null | head -n1)"
  if [ -n "$hit" ]; then echo "maybe|${hit#$VAULT/}"; return; fi
  echo "none|"
}

log "Scanning for PDFs under: ${SCAN_DIR#$VAULT/}"
TOTAL=0; EXTRACTED=0; NEEDS_OCR=0; HAS_SUMMARY=0; GAP=0

{
  echo "---"
  echo "type: note"
  echo "tags: [system, import, slides]"
  echo "date: $(date +%F)"
  echo "---"
  echo
  echo "# Slides Report"
  echo
  echo "> Generated by \`extract-pdfs.sh\` on $(date '+%Y-%m-%d %H:%M'). Scanned: \`$SCAN_DIR\`"
  echo "> \`/summarize-slides\` uses this to fill in summaries for decks marked **none**."
  echo "> Extracted text cache: \`_Import-Staging/.pdf-text/\`"
  echo
  echo "| Slide deck | Course (folder) | Pages | Text | Existing summary | Cache |"
  echo "|---|---|---|---|---|---|"
} > "$REPORT"

while IFS= read -r -d '' pdf; do
  TOTAL=$((TOTAL+1))
  rel="${pdf#$SCAN_DIR/}"
  course="$(basename "$(dirname "$pdf")")"
  out="$CACHE/${rel}.txt"
  mkdir -p "$(dirname "$out")"

  if [ -s "$out" ] && [ "$FORCE" -eq 0 ]; then
    chars="$(wc -m < "$out" | tr -d ' ')"
  else
    chars="$(extract_text "$pdf" "$out")"
  fi

  textstatus="text"
  if [ "${chars:-0}" -lt "$MIN_CHARS" ]; then
    if [ "$DO_OCR" -eq 1 ]; then
      chars="$(ocr_pdf "$pdf" "$out")"
      if [ "${chars:-0}" -lt "$MIN_CHARS" ]; then textstatus="empty"; NEEDS_OCR=$((NEEDS_OCR+1)); else textstatus="ocr"; fi
    else
      textstatus="needs-OCR"; NEEDS_OCR=$((NEEDS_OCR+1))
    fi
  fi
  if [ "$textstatus" = "text" ] || [ "$textstatus" = "ocr" ]; then EXTRACTED=$((EXTRACTED+1)); fi

  pages="?"
  if have pdfinfo; then pages="$(pdfinfo "$pdf" 2>/dev/null | awk '/^Pages:/{print $2}')"; fi

  sumres="$(find_summary "$pdf")"
  sumstatus="${sumres%%|*}"; sumcand="${sumres#*|}"
  case "$sumstatus" in
    yes)   HAS_SUMMARY=$((HAS_SUMMARY+1)); sumcell="yes: $sumcand" ;;
    maybe) sumcell="maybe: $sumcand" ;;
    none)  GAP=$((GAP+1)); sumcell="none - needs summary" ;;
  esac

  printf '| %s | %s | %s | %s | %s | `%s` |\n' \
    "$rel" "$course" "${pages:-?}" "$textstatus" "$sumcell" "${out#$VAULT/}" >> "$REPORT"
done < <(find "$SCAN_DIR" -type f -iname '*.pdf' -print0 2>/dev/null | sort -z)

{
  echo
  echo "## Summary"
  echo
  echo "- Slide decks found: **$TOTAL**"
  echo "- Text extracted: **$EXTRACTED**"
  echo "- Need OCR (scanned/image-only): **$NEEDS_OCR**"
  echo "- Already have a summary note: **$HAS_SUMMARY**"
  echo "- **Gaps to summarise (no note yet): $GAP**"
  echo
  echo "Run \`hal\` then \`/summarize-slides\` to generate notes for the **$GAP** gap decks."
  [ "$NEEDS_OCR" -gt 0 ] && echo && echo "_Re-run with \`--ocr\` (and \`sudo apt install tesseract-ocr\`) to read the scanned ones._"
} >> "$REPORT"

cat <<EOF

${c_green}Slide extraction complete.${c_off}
  Decks found:        $TOTAL
  Text extracted:     $EXTRACTED
  Need OCR:           $NEEDS_OCR $( [ "$NEEDS_OCR" -gt 0 ] && [ "$DO_OCR" -eq 0 ] && printf '%s(re-run with --ocr)%s' "$c_yellow" "$c_off" )
  Already summarised: $HAS_SUMMARY
  ${c_yellow}Gaps to summarise:  $GAP${c_off}

Report: ${REPORT#$VAULT/} (open it in Obsidian)
Next:   hal  ->  /summarize-slides
EOF
